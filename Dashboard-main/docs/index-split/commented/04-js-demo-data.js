// หน้าที่: สร้างข้อมูลสุ่มหน้าตาเหมือนตารางจริง ใช้เมื่อยังไม่เชื่อมต่อฐานข้อมูล (โหมดทดลอง)
// ผลลัพธ์: อ็อบเจ็กต์ D ที่มีอาร์เรย์ของแต่ละตาราง เช่น D.daily, D.hourly, D.ward ...
