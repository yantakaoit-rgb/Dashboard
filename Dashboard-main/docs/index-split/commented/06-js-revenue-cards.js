document.addEventListener('click',e=>{ // ดักการคลิกทั้งหน้า (event delegation) เพราะปุ่มถูกสร้างใหม่ทุกครั้งที่วาดการ์ด
  const el=e.target&&e.target.closest?e.target:null; // องค์ประกอบที่ถูกคลิก (กันกรณีไม่ใช่ element)
  if(!el)return; // ไม่ใช่ element ให้ออก
  const v=el.closest('[data-dpv]'); // หาปุ่มสลับมุมมองที่ถูกคลิก (ถ้ามี)
  const t=el.closest('[data-dpt]'); // หาปุ่มเลือกประเภทผู้ป่วยที่ถูกคลิก (ถ้ามี)
  if(v){ // ถ้าคลิกโดนปุ่มสลับมุมมอง
    DPV=v.dataset.dpv; // เปลี่ยนมุมมองตามค่าในปุ่ม ('dept' หรือ 'pt')
    dpRender(); // วาดการ์ดใหม่
  } // จบกรณีคลิกปุ่มมุมมอง
  if(t){ // ถ้าคลิกโดนปุ่มประเภทผู้ป่วย
    DPT=t.dataset.dpt; // เปลี่ยนประเภทผู้ป่วยตามค่าในปุ่ม ('opd' / 'ipd' / 'all')
    dpRender(); // วาดการ์ดใหม่
  } // จบกรณีคลิกปุ่มประเภทผู้ป่วย
}); // จบตัวดักคลิก

