// หน้าที่: (1) แสดงกล่องคำอธิบายลอยตามเมาส์/นิ้ว (2) ขยาย/ย่อกล่อง 3D เต็มจอ (3) ปิด/เปิดการแสดงผล 3D
// ตัวแปรที่ใช้จากส่วนอื่น: tip (กล่อง tooltip), onEl (องค์ประกอบที่กำลังชี้อยู่)
// หมายเหตุ: แตกบรรทัดที่เดิมอัดหลายคำสั่งให้เป็นหนึ่งคำสั่งต่อบรรทัด เพื่อ comment ได้ทุกบรรทัด (พฤติกรรมเท่าเดิม)
