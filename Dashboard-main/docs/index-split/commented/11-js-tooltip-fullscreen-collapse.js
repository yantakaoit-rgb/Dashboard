function onPtr(e) { // จัดการเมื่อเมาส์/นิ้วเคลื่อนหรือกด (e = เหตุการณ์ pointer) เพื่อแสดง/ซ่อน tooltip
  const el = e.target.closest ? e.target.closest('[data-tip]') : null; // el = องค์ประกอบที่ชี้อยู่ (หรือพ่อแม่ใกล้สุด) ที่มี data-tip ถ้าไม่มีเป็น null
  if (onEl) { // ถ้ามีองค์ประกอบที่เคยถูกเน้นไว้ก่อนหน้า
    onEl.classList.remove('on'); // เอาสถานะเน้น (on) ออก
  } // จบเงื่อนไข
  if (!el) { // ถ้าตอนนี้ไม่ได้ชี้ที่อะไรที่มี tooltip
    tip.style.display = 'none'; // ซ่อนกล่อง tooltip
    onEl = null; // ล้างองค์ประกอบที่จำไว้
    return; // เลิกทำงาน
  } // จบเงื่อนไขไม่มี tooltip
  el.classList.add('on'); // เน้นองค์ประกอบที่ชี้อยู่
  onEl = el; // จำองค์ประกอบนี้ไว้ เพื่อเอาการเน้นออกในรอบถัดไป
  tip.innerHTML = el.dataset.tip; // ใส่ข้อความ (HTML) จาก data-tip ลงกล่อง tooltip
  tip.style.display = 'block'; // แสดงกล่อง tooltip
  const r = tip.getBoundingClientRect(); // r = ขนาดกล่อง tooltip จริง (ใช้คำนวณไม่ให้ล้นจอ)
  let l = e.clientX + 16; // l = ตำแหน่งซ้าย: ถัดจากเมาส์ไปทางขวา 16px
  let t = e.clientY + 16; // t = ตำแหน่งบน: ใต้เมาส์ลงไป 16px
  if (l + r.width > innerWidth - 8) { // ถ้ากล่องจะล้นขอบขวาของจอ
    l = e.clientX - r.width - 16; // ย้ายไปอยู่ด้านซ้ายของเมาส์
  } // จบการกันล้นขวา
  if (t + r.height > innerHeight - 8) { // ถ้ากล่องจะล้นขอบล่างของจอ
    t = e.clientY - r.height - 16; // ย้ายไปอยู่เหนือเมาส์
  } // จบการกันล้นล่าง
  tip.style.left = Math.max(8, l) + 'px'; // ตั้งตำแหน่งซ้าย (ห่างขอบจออย่างน้อย 8px)
  tip.style.top = Math.max(8, t) + 'px'; // ตั้งตำแหน่งบน (ห่างขอบจออย่างน้อย 8px)
} // จบ onPtr

document.addEventListener('pointermove', onPtr); // เมื่อเลื่อนเมาส์/นิ้ว -> อัปเดต tooltip
document.addEventListener('pointerdown', onPtr); // เมื่อกด/แตะ -> อัปเดต tooltip (รองรับมือถือ)
document.addEventListener('scroll', () => { tip.style.display = 'none'; }, true); // เมื่อเลื่อนหน้า (ดักทุกชั้นด้วย true) -> ซ่อน tooltip

/* ===== ส่วน 3D (โหลดเมื่อเลื่อนมาถึง) ===== */
/* ===== ปุ่มย่อ/ขยายการแสดงผล 3D: ขยายเต็มจอ ⇄ ย่อกลับขนาดเดิม (ใช้ร่วมกันทั้งฉากห้องบริการและการ์ดอาคาร) =====
   ย้ายกล่องไปไว้ชั้นนอกสุดของหน้าชั่วคราว (เหลือตัวกั้นที่ไว้ที่เดิม) จึงไม่ถูกการ์ดแม่บัง · กด Esc หรือกดปุ่มเดิมเพื่อย่อกลับ
   ถ้าเบราว์เซอร์ไม่รองรับโหมดเต็มจอจริง (เช่น iPhone) จะขยายเต็มหน้าต่างแทน · el=กล่องที่จะขยาย, btn=ปุ่ม, back=ฟังก์ชันคืนที่วางสำรองถ้าตัวกั้นหาย */
function fsBox(el, btn, back) { // ผูกพฤติกรรมเต็มจอให้กล่อง el ด้วยปุ่ม btn (back = ฟังก์ชันหาที่วางสำรองตอนย่อกลับ)
  if (!el || !btn) { // ถ้าไม่มีกล่องหรือไม่มีปุ่ม
    return; // ไม่ทำอะไร
  } // จบเงื่อนไข
  const root = document.documentElement; // root = แท็ก <html> (ใช้ขอเต็มจอและล็อกการเลื่อนหน้า)
  const on = () => el.classList.contains('fsx'); // on() = ตอนนี้กล่องอยู่ในโหมดเต็มจอหรือไม่ (ดูจากคลาส fsx)
  const paint = () => { // paint = อัปเดตข้อความ/คำอธิบาย/สถานะของปุ่มตามโหมดปัจจุบัน
    const f = on(); // f = อยู่โหมดเต็มจอหรือไม่
    const s = f ? 'ย่อกลับขนาดเดิม (Esc)' : 'ขยายเต็มจอ'; // s = ข้อความอธิบายปุ่ม
    btn.textContent = f ? '⤡ ย่อกลับ' : '⛶ เต็มจอ'; // ข้อความบนปุ่ม
    btn.title = s; // tooltip ของปุ่ม
    btn.setAttribute('aria-label', s); // ข้อความสำหรับโปรแกรมอ่านหน้าจอ
    btn.setAttribute('aria-pressed', f ? 'true' : 'false'); // บอกสถานะกดอยู่/ไม่อยู่ (การเข้าถึง)
  }; // จบ paint
  function enter() { // เข้าโหมดเต็มจอ
    if (on() || !el.parentNode) { // ถ้าอยู่โหมดเต็มจออยู่แล้ว หรือกล่องไม่ได้อยู่ในหน้า
      return; // ไม่ทำอะไร
    } // จบเงื่อนไข
    const ph = document.createElement('div'); // ph = ตัวกั้นที่ (placeholder) ไว้แทนกล่องเดิม
    ph.style.cssText = 'width:100%;height:' + el.offsetHeight + 'px'; // ให้ตัวกั้นสูงเท่ากล่องเดิม // ตัวกั้นที่ไว้ไม่ให้หน้าเลื่อนกระโดด
    el.parentNode.insertBefore(ph, el); // วางตัวกั้นไว้ที่เดิมของกล่อง
    el._fsph = ph; // จำตัวกั้นไว้กับกล่อง เพื่อใช้คืนที่ตอนย่อกลับ
    document.body.appendChild(el); // ย้ายกล่องไปชั้นนอกสุดของหน้า (กันถูกการ์ดแม่บัง)
    el.classList.add('fsx'); // ใส่คลาสโหมดเต็มจอให้กล่อง
    root.classList.add('fsx-lock'); // ล็อกการเลื่อนหน้าหลัก
    if (root.requestFullscreen) { // ถ้าเบราว์เซอร์รองรับเต็มจอจริง
      root.requestFullscreen().catch(() => { }); // ขอเต็มจอจริง (ถ้าถูกปฏิเสธก็เงียบไว้) // เต็มจอจริงถ้าทำได้ ไม่ได้ก็ใช้เต็มหน้าต่าง
    } // จบเงื่อนไขรองรับเต็มจอ
    paint(); // อัปเดตปุ่มเป็นสถานะ "ย่อกลับ"
  } // จบ enter
  function leave() { // ออกจากโหมดเต็มจอ (ย่อกลับ)
    if (!on()) { // ถ้าไม่ได้อยู่โหมดเต็มจอ
      return; // ไม่ทำอะไร
    } // จบเงื่อนไข
    el.classList.remove('fsx'); // เอาคลาสโหมดเต็มจอออก
    root.classList.remove('fsx-lock'); // ปลดล็อกการเลื่อนหน้า
    const ph = el._fsph; // ph = ตัวกั้นที่ที่เก็บไว้ตอนเข้าโหมด
    el._fsph = null; // ล้างค่าที่จำไว้
    if (ph && ph.isConnected) { // ถ้าตัวกั้นยังอยู่ในหน้า
      ph.replaceWith(el); // ให้กล่องกลับมาแทนที่ตัวกั้น (คืนที่เดิม)
    } else { // ถ้าตัวกั้นหายไป
      const h = back && back(); // h = ที่วางสำรองจากฟังก์ชัน back (ถ้ามี) // ตัวกั้นหาย (หน้าถูกวาดใหม่) → ใช้ที่วางสำรอง
      if (h) { // ถ้าได้ที่วางสำรอง
        h.appendChild(el); // ใส่กล่องกลับในที่วางสำรอง
      } // จบเงื่อนไขมีที่สำรอง
    } // จบการคืนที่
    if (document.fullscreenElement && document.exitFullscreen) { // ถ้าตอนนี้อยู่เต็มจอจริงและออกได้
      document.exitFullscreen().catch(() => { }); // ออกจากเต็มจอจริง (เงียบถ้าล้มเหลว)
    } // จบเงื่อนไขออกเต็มจอจริง
    paint(); // อัปเดตปุ่มเป็นสถานะ "เต็มจอ"
  } // จบ leave
  btn.addEventListener('click', () => on() ? leave() : enter()); // คลิกปุ่ม: ถ้าเต็มจออยู่ -> ย่อกลับ, ไม่เต็มจอ -> ขยาย
  document.addEventListener('fullscreenchange', () => { // เมื่อสถานะเต็มจอจริงของเบราว์เซอร์เปลี่ยน
    if (!document.fullscreenElement && on()) { // ถ้าออกจากเต็มจอจริงแล้ว แต่กล่องยังอยู่โหมดเต็ม
      leave(); // ย่อกลับด้วย
    } // จบเงื่อนไข
  }); // กด Esc ออกจากเต็มจอจริง → ย่อกลับด้วย
  document.addEventListener('keydown', e => { // เมื่อกดแป้นพิมพ์
    if (e.key === 'Escape' && on()) { // ถ้าเป็น Esc และกล่องอยู่โหมดเต็ม
      leave(); // ย่อกลับ
    } // จบเงื่อนไข
  }); // โหมดเต็มหน้าต่าง (กรณีไม่มีเต็มจอจริง เช่น iPhone)
  paint(); // ตั้งค่าปุ่มให้ตรงสถานะเริ่มต้น
} // จบ fsBox

/* ===== ปุ่มย่อ/ขยาย = ปิด/เปิดการแสดงผล 3D (ติดที่หัวการ์ด ปุ่มอยู่ตลอดแม้ปิดอยู่) =====
   ปิด → ซ่อนฉาก 3D ทั้งหมด เหลือแต่หัวการ์ด · ฉากหยุดวาดอัตโนมัติ (ประหยัด CPU/GPU) และถ้ายังไม่เคยเปิดจะไม่โหลด three.js
   จำค่าที่เลือกไว้ในเบราว์เซอร์ (key) · sec=การ์ดที่มีหัว .h */
function clBox(sec, key) { // ผูกปุ่มปิด/เปิดการแสดงผล 3D ให้การ์ด sec และจำสถานะไว้ในเบราว์เซอร์ด้วยคีย์ key
  const h = sec && sec.querySelector('.h'); // h = หัวการ์ด (.h) ที่จะวางปุ่ม
  if (!h) { // ถ้าไม่มีการ์ดหรือไม่มีหัวการ์ด
    return; // ไม่ทำอะไร
  } // จบเงื่อนไข
  let b = h.querySelector('.cltg'); // b = ปุ่มปิด/เปิดที่อาจมีอยู่แล้ว (ถ้าไม่มีเป็น null)
  function set(c, save) { // ตั้งสถานะ: c=true → ปิดการแสดงผล, save=true → บันทึกลงเบราว์เซอร์
    sec.classList.toggle('cl3', c); // เปิด/ปิดคลาส cl3 ที่ใช้ซ่อนฉาก 3D
    b.textContent = c ? '▸ เปิดการแสดงผล 3D' : '▾ ปิดการแสดงผล 3D'; // ข้อความบนปุ่มตามสถานะ
    b.title = c ? 'เปิดการแสดงผล 3D อีกครั้ง' : 'ปิดการแสดงผล 3D (ซ่อนฉาก ประหยัดเครื่อง)'; // tooltip ของปุ่ม
    b.setAttribute('aria-expanded', c ? 'false' : 'true'); // บอกสถานะขยาย/ยุบ (การเข้าถึง)
    if (save) { // ถ้าต้องบันทึกสถานะ
      try { // กันกรณีเบราว์เซอร์ห้ามใช้ localStorage
        localStorage.setItem(key, c ? '1' : '0'); // บันทึก '1' = ปิดอยู่, '0' = เปิดอยู่
      } catch (e) { } // ถ้าบันทึกไม่ได้ ก็ข้ามไป
    } // จบเงื่อนไขบันทึก
  } // จบ set
  if (!b) { // ถ้ายังไม่มีปุ่มในหัวการ์ด
    b = document.createElement('button'); // สร้างปุ่มใหม่
    b.type = 'button'; // กำหนดเป็นปุ่มธรรมดา (ไม่ส่งฟอร์ม)
    b.className = 'cltg'; // ตั้งคลาสให้ใช้สไตล์ปุ่มนี้และค้นหาเจอรอบหน้า
    h.appendChild(b); // ต่อปุ่มท้ายหัวการ์ด
  } // จบการสร้างปุ่ม
  b.onclick = () => set(!sec.classList.contains('cl3'), true); // คลิกปุ่ม: สลับสถานะและบันทึก
  sec._cl = set; // ให้ส่วนอื่นสั่งเปิด/ปิดได้ (เช่นปุ่ม 3D ▾ บนหัวหน้า)
  let c0 = false; // c0 = สถานะเริ่มต้น (ค่าตั้งต้น: เปิดอยู่)
  try { // กันกรณีอ่าน localStorage ไม่ได้
    c0 = localStorage.getItem(key) === '1'; // อ่านค่าที่เคยบันทึกไว้ ('1' = เคยปิดไว้)
  } catch (e) { } // ถ้าอ่านไม่ได้ ใช้ค่าตั้งต้น
  set(c0, false); // ตั้งสถานะเริ่มต้น (ไม่ต้องบันทึกซ้ำ)
} // จบ clBox

clBox(document.getElementById('s3d'), 'v3cl'); // การ์ดห้องบริการ 3 มิติ
