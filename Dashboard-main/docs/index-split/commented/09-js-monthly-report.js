const xmon = k => ['ม.ค.', 'ก.พ.', 'มี.ค.', 'เม.ย.', 'พ.ค.', 'มิ.ย.', 'ก.ค.', 'ส.ค.', 'ก.ย.', 'ต.ค.', 'พ.ย.', 'ธ.ค.'][+k.slice(5) - 1] + ' ' + String(+k.slice(0, 4) + 543).slice(2); // แปลงคีย์ "YYYY-MM" เป็น "เดือนย่อไทย + ปี พ.ศ. 2 หลัก" เช่น 2026-03 -> "มี.ค. 69"

function xbars(ser, lab, d = 0) { // วาดกราฟแท่ง SVG (ser = ชุดข้อมูล [{v:[ค่า...], c:สี}], lab = ป้ายแกน x, d = จำนวนทศนิยม)
  const W = NARROW() ? 360 : 700; // W = ความกว้างกราฟ (จอแคบ 360, จอปกติ 700)
  const H = 270; // H = ความสูงกราฟ
  const B = 30; // B = ขอบล่างเว้นไว้ใส่ป้ายแกน x
  const T = 16; // T = ขอบบนเว้นไว้
  const n = lab.length; // n = จำนวนแท่งต่อชุด (จำนวนเดือน)
  const single = ser.length === 1; // single = true ถ้ามีชุดข้อมูลเดียว (จะแสดงตัวเลขบนแท่งด้วย)
  const top = Math.max(1, ...ser.flatMap(x => x.v)); // top = ค่าสูงสุดของทุกชุด (อย่างน้อย 1 กันหารศูนย์)
  const vt = single ? ser[0].v.map(v => fm(v, d)) : []; // vt = ข้อความตัวเลขบนแท่ง (เฉพาะกรณีชุดเดียว)
  const maxLen = vt.length ? Math.max(...vt.map(t => t.length)) : 0; // maxLen = ความยาวตัวเลขที่ยาวที่สุด
  const cw0 = (W - 62) / Math.max(n, 1); // cw0 = ความกว้างต่อช่องแบบประมาณ (ก่อนรู้ความกว้างป้ายแกน y)
  const rot = single && n <= 14 && cw0 * .96 / (maxLen * .58) < 7.5; // rot = true ถ้าตัวเลขยาวเกินช่อง -> หมุนข้อความเป็นแนวตั้ง
  const room = rot ? (maxLen * 6 + 14) / (H - T - B) : .12; // room = สัดส่วนที่เว้นเหนือแท่งสูงสุดไว้ใส่ตัวเลข (หมุนแล้วต้องเว้นมากขึ้น)
  const mx = top * (1 + Math.max(room, .12)); // mx = ค่าสูงสุดของแกน y (เผื่อพื้นที่ด้านบน อย่างน้อย 12%)
  const ticks = [0, 1, 2, 3, 4].map(i => fr(mx * (1 - i / 4), mx < 10 ? 1 : 0)); // ticks = ป้ายแกน y 5 ระดับ จากมากไปน้อย (ค่าน้อยกว่า 10 ใช้ 1 ทศนิยม)
  const L = Math.max(46, Math.max(...ticks.map(t => t.length)) * 6.4 + 12); // L = ขอบซ้ายสำหรับป้ายแกน y (ขั้นต่ำ 46 ปรับตามความยาวป้าย)
  const cw = (W - L) / Math.max(n, 1); // cw = ความกว้างต่อช่องจริงของแต่ละเดือน
  const bw = Math.min(40, cw * .72 / ser.length); // bw = ความกว้างแท่ง (สูงสุด 40 และแบ่งตามจำนวนชุด)
  let g = ''; // g = สะสมข้อความ SVG ทั้งหมดที่จะวาด
  ticks.forEach((t, i) => { // วนวาดเส้นตารางและป้ายแกน y ทีละระดับ
    const y = T + (H - T - B) * i / 4; // y = ตำแหน่งแนวตั้งของเส้นระดับนี้
    g += `<line x1="${L}" x2="${W}" y1="${y}" y2="${y}" stroke="#e2eaf2"/>`; // เพิ่มเส้นตารางแนวนอน
    g += `<text x="${L - 6}" y="${y + 4}" font-size="11" text-anchor="end" fill="#60758a">${t}</text>`; // เพิ่มป้ายตัวเลขแกน y ชิดขวาของขอบซ้าย
  }); // จบการวาดเส้นตาราง
  ser.forEach((x, si) => x.v.forEach((v, i) => { // วนทุกชุด (si = ลำดับชุด) และทุกค่า (i = ลำดับเดือน) เพื่อวาดแท่ง
    const h = (H - T - B) * v / mx; // h = ความสูงแท่งตามสัดส่วนค่า
    const px = L + cw * i + (cw - bw * ser.length) / 2 + bw * si; // px = ตำแหน่งแนวนอนของแท่ง (จัดกึ่งกลางช่อง, ชุดถัดไปเลื่อนขวา)
    const y = H - B - h; // y = ตำแหน่งบนสุดของแท่ง (วัดจากขอบล่าง)
    g += `<rect x="${px}" y="${y}" width="${bw - 2}" height="${h}" rx="5" fill="${x.c}"><title>${lab[i]}: ${fm(v, d)}</title></rect>`; // วาดแท่งมุมมน พร้อม tooltip แสดงเดือนและค่า
    if (single && n <= 14) { // ถ้าชุดเดียวและไม่เกิน 14 แท่ง ให้แสดงตัวเลขบนแท่ง
      const cx = L + cw * i + cw / 2; // cx = กึ่งกลางช่องของเดือนนี้
      const t = vt[i]; // t = ข้อความตัวเลขของแท่งนี้
      if (rot) { // กรณีตัวเลขยาว: หมุนข้อความเป็นแนวตั้ง
        g += `<text transform="rotate(-90 ${cx + 4} ${y - 6})" x="${cx + 4}" y="${y - 6}" font-size="10.5" fill="#0b1f33">${t}</text>`; // ข้อความหมุน -90 องศา เหนือแท่ง
      } else { // กรณีตัวเลขพอดีช่อง: วางแนวนอน
        g += `<text x="${cx}" y="${y - 6}" font-size="${Math.min(11, cw * .96 / (t.length * .58)).toFixed(2)}" text-anchor="middle" fill="#0b1f33">${t}</text>`; // ข้อความกึ่งกลางเหนือแท่ง ลดขนาดตัวอักษรให้พอดีช่อง (สูงสุด 11)
      } // จบเลือกแนวข้อความ
    } // จบการแสดงตัวเลขบนแท่ง
  })); // จบการวาดแท่งทุกชุดทุกเดือน
  const st = Math.ceil(n / 14); // st = ก้าวข้ามป้ายแกน x (ถ้าเกิน 14 เดือนจะแสดงเว้นช่อง)
  lab.forEach((l, i) => { // วนทุกป้ายเดือน
    if (i % st == 0) { // แสดงเฉพาะป้ายที่ตรงก้าว
      g += `<text x="${L + cw * i + cw / 2}" y="${H - 10}" font-size="11" text-anchor="middle" fill="#60758a">${l}</text>`; // เพิ่มป้ายเดือนใต้แท่งกึ่งกลางช่อง
    } // จบเงื่อนไขก้าว
  }); // จบการวาดป้ายแกน x
  return `<svg viewBox="0 0 ${W} ${H}" width="100%"><defs><linearGradient id="xg" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#2dd4bf"/><stop offset="1" stop-color="#2563eb"/></linearGradient></defs>${g}</svg>`; // คืน SVG สมบูรณ์ พร้อมนิยามไล่สี xg (เขียวน้ำทะเล -> น้ำเงิน) ให้แท่งอ้างถึง
} // จบ xbars

const xsec = (n, t, s, b) => `<section class="s w12" id="sec${n}"><div class="h"><b>${n}</b><h2>${t}</h2><span>${s}</span></div>${b}</section>`; // สร้างการ์ดหัวข้อ (n=เลขหัวข้อ, t=ชื่อไทย, s=ชื่ออังกฤษ, b=เนื้อหา HTML)

function xmonthly(rows, t) { // รวมข้อมูลรายวันเป็นรายเดือน (rows = แถวรายวัน, t = ตัวชี้วัดที่เลือก {k:ชื่อคอลัมน์, g:'sum'|'avg'})
  const m = {}; // m = ตารางเดือน -> {s: ผลรวม, n: จำนวนวันที่มีข้อมูล}
  rows.forEach(r => { // วนทุกแถวรายวัน
    const v = r[t.k]; // v = ค่าของตัวชี้วัดในวันนั้น
    if (v === '' || v == null || isNaN(+v)) { // ถ้าค่าว่างหรือไม่ใช่ตัวเลข
      return; // ข้ามวันนี้
    } // จบเงื่อนไขข้าม
    const k = String(r.record_date).slice(0, 7); // k = เดือนของวันนั้นในรูป "YYYY-MM"
    const o = m[k] ??= { s: 0, n: 0 }; // o = ตัวสะสมของเดือนนี้ (สร้างใหม่ถ้ายังไม่มี)
    o.s += +v; // บวกค่าเข้าผลรวมเดือน
    o.n++; // นับจำนวนวันที่มีข้อมูล
  }); // จบการสะสมรายเดือน
  return Object.keys(m).sort().map(k => ({ // เรียงเดือนจากเก่าไปใหม่ แล้วแปลงเป็นรายการผลลัพธ์
    k, // คีย์เดือน
    n: m[k].n, // จำนวนวันที่มีข้อมูล
    v: t.g == 'sum' ? m[k].s : m[k].s / m[k].n // ค่าของเดือน: ชนิด sum = ผลรวม, อย่างอื่น = เฉลี่ยต่อวัน
  })); // จบการแปลงผลลัพธ์
} // จบ xmonthly

function xDraw() { // วาดชิปเลือกตัวชี้วัด + กราฟ + ตารางของรายงานรายเดือน (ใช้ตัวชี้วัดปัจจุบัน xk)
  const ms = xmonthly(XD.daily, xk); // ms = ข้อมูลรายเดือนของตัวชี้วัดที่เลือก
  $('#xchips').innerHTML = XT.map(t => `<button class="${t === xk ? 'on' : ''}" data-k="${t.k}">${t.n}</button>`).join(''); // สร้างปุ่มตัวชี้วัดทั้งหมด (ปุ่มที่เลือกอยู่ใส่คลาส on)
  $('#xchart').innerHTML = ms.length // ใส่กราฟลงกล่อง #xchart
    ? xbars([{ v: ms.map(x => x.v), c: 'url(#xg)' }], ms.map(x => xmon(x.k)), xk.d || 0) // มีข้อมูล -> วาดกราฟแท่งสีไล่ระดับ ป้ายเป็นเดือนไทย
    : '<div class="nd">ไม่มีข้อมูล</div>'; // ไม่มีข้อมูล -> แสดงข้อความแทน
  const head = `<tr><th>เดือน</th><th>${xk.u}${xk.g == 'avg' ? ' (เฉลี่ย/วัน)' : ' (รวม)'}</th><th>เทียบเดือนก่อน</th><th>วันที่มีข้อมูล</th></tr>`; // head = แถวหัวตาราง (หน่วยของตัวชี้วัด + บอกว่าเป็นค่าเฉลี่ยหรือรวม)
  const body = ms.map((x, i) => { // body = แถวข้อมูลของแต่ละเดือน
    const p = i ? ms[i - 1].v : 0; // p = ค่าของเดือนก่อนหน้า (เดือนแรกไม่มี = 0)
    const c = p ? (x.v - p) / p * 100 : null; // c = % เปลี่ยนแปลงเทียบเดือนก่อน (ไม่มีเดือนก่อนเป็น null)
    return `<tr><td>${xmon(x.k)}</td>` + // ช่องชื่อเดือน
      `<td><b>${fm(x.v, xk.d || 0)}</b></td>` + // ช่องค่าของเดือน (ตัวหนา)
      `<td class="${c == null ? '' : c >= 0 ? 'up' : 'dn'}">${c == null ? '-' : (c >= 0 ? '▲ ' : '▼ ') + fm(Math.abs(c), 1) + '%'}</td>` + // ช่องเทียบเดือนก่อน: ขึ้น ▲ / ลง ▼ พร้อม % และคลาสสี up/dn
      `<td>${x.n}</td></tr>`; // ช่องจำนวนวันที่มีข้อมูล แล้วปิดแถว
  }).reverse().join(''); // กลับลำดับให้เดือนล่าสุดอยู่บนสุด แล้วต่อเป็นข้อความเดียว
  $('#xtab').innerHTML = head + body; // ใส่หัวตาราง + แถวข้อมูลลงตาราง #xtab
} // จบ xDraw

async function xtra() { // สร้างส่วน "รายงานรายเดือน" ต่อท้ายหน้า (โหลดข้อมูลตั้งแต่ 2025-10-01 ถึงวันนี้ครั้งแรกครั้งเดียว)
  document.querySelectorAll('.xs').forEach(e => e.remove()); // ลบส่วนรายงานเดิมที่เคยสร้างไว้ (กันซ้ำเมื่อเรียกใหม่)
  const host = document.querySelector('main'); // host = แท็ก <main> ที่จะเอาส่วนใหม่ไปต่อท้าย
  if (!host) { // ถ้าไม่พบ <main>
    return; // เลิกทำงาน
  } // จบเงื่อนไขไม่พบ main
  const mk = h => { // mk = ฟังก์ชันสร้างกล่องห่อ HTML แล้วต่อท้าย <main>
    const d = document.createElement('div'); // d = div ใหม่
    d.className = 'xs'; // ตั้งคลาส xs เพื่อให้ลบทิ้งได้ภายหลัง
    d.style.display = 'contents'; // ให้กล่องห่อไม่กระทบเลย์เอาต์ (ลูกทำตัวเหมือนอยู่ใน main โดยตรง)
    d.innerHTML = h; // ใส่เนื้อหา HTML
    host.append(d); // ต่อท้ายใน <main>
  }; // จบ mk
  try { // ครอบการโหลดข้อมูลเพื่อดักข้อผิดพลาด
    if (!XD) { // ถ้ายังไม่เคยโหลดข้อมูลรายเดือน
      const a = '2025-10-01'; // a = วันเริ่มต้นของรายงาน
      const b = iso(new Date()); // b = วันนี้ (รูปแบบ YYYY-MM-DD)
      XD = { daily: await get('daily', a, b) }; // โหลดข้อมูลรายวันทั้งช่วงแล้วเก็บไว้ใน XD (ใช้ซ้ำภายหลัง)
    } // จบการโหลดครั้งแรก
    if (!XD.daily.length) { // ถ้าโหลดมาแล้วไม่มีข้อมูล
      mk(xsec(19, 'รายงานรายเดือน', 'Monthly Report', '<div class="nd">ยังไม่มีข้อมูลรายเดือน</div>')); // แสดงการ์ดบอกว่ายังไม่มีข้อมูล
      return; // จบการทำงาน
    } // จบเงื่อนไขไม่มีข้อมูล
    mk(xsec(19, 'รายงานรายเดือน', 'Monthly Report', `<div class="tg" id="xchips" style="margin-bottom:12px"></div><div id="xchart"></div><div style="overflow-x:auto;margin-top:12px"><table id="xtab"></table></div>`)); // สร้างการ์ดรายงาน: ที่ใส่ปุ่มเลือก, ที่ใส่กราฟ, ที่ใส่ตาราง
    $('#xchips').onclick = e => { // เมื่อคลิกในพื้นที่ปุ่มตัวชี้วัด
      const k = e.target.dataset.k; // k = คีย์ตัวชี้วัดของปุ่มที่คลิก (ถ้าไม่ได้คลิกที่ปุ่มจะเป็น undefined)
      if (k) { // ถ้าคลิกโดนปุ่ม
        xk = XT.find(t => t.k === k); // เปลี่ยนตัวชี้วัดปัจจุบัน
        xDraw(); // วาดกราฟและตารางใหม่
      } // จบเงื่อนไขคลิกโดนปุ่ม
    }; // จบตัวจัดการคลิก
    xDraw(); // วาดกราฟและตารางครั้งแรก
  } catch (e) { // ถ้าโหลดหรือวาดล้มเหลว
    mk(xsec(19, 'รายงานรายเดือน', 'Monthly Report', `<div class="nd">โหลดข้อมูลไม่สำเร็จ: ${String(e.message).replace(/[<>]/g, '')}</div>`)); // แสดงข้อความผิดพลาด (ตัด < > ออกกัน HTML แทรก)
  } // จบ try/catch
} // จบ xtra
